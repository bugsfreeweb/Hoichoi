"""Build the bundled Bangla font package from the root `Bangla Fonts` zips.

Only Unicode faces are kept: the ANSI/Bijoy variants map Bengali bytes to the
wrong code points, so bundling them would produce garbled text in a browser.
Every face is subset to Bengali + Latin + the punctuation the site actually
uses, then written as WOFF2. Original readmes/terms travel with the files.
"""
import io
import json
import os
import re
import shutil
import subprocess
import unicodedata
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / "Bangla Fonts"
OUT = ROOT / "packages" / "bangla-fonts"
FILES = OUT / "files"
LICENSES = OUT / "licenses"
FILES.mkdir(parents=True, exist_ok=True)
LICENSES.mkdir(parents=True, exist_ok=True)

inventory = json.loads((ROOT / "packages" / "bangla-fonts" / "scripts" / "font-inventory.json").read_text(encoding="utf-8"))

DROP = ["Unicode", "UNI & BE", "Italic", "Iltali", "Itali", "italic"]


def clean_label(name: str) -> str:
    name = name.replace("\u200d", "").replace("_", " ")
    for token in DROP:
        name = re.sub(re.escape(token), " ", name, flags=re.I)
    name = re.sub(r"\s+", " ", name).strip(" -_")
    return name


def slug(name: str) -> str:
    norm = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode()
    s = re.sub(r"[^a-z0-9]+", "-", norm.lower()).strip("-")
    return s or "font"


groups: dict[str, dict] = {}
for face in inventory:
    if not face.get("bengali"):
        continue
    label = clean_label(face["family"])
    # A couple of zips ship genuinely distinct families (three Ashalota cuts,
    # two Momenshahi matra styles); everything else is one family whose italic
    # face merely names itself differently. Grouping by zip keeps those siblings
    # together instead of inventing a "… c" family from a half-stripped name.
    split_zips = {"SabbirAshalota.zip", "FNAbdullahMomenshahi.zip"}
    group_key = f"{face['zip']}::{label}" if face["zip"] in split_zips else face["zip"]
    fid = slug(label)
    weight = int(face.get("weight") or 400)
    italic = bool(face.get("italic")) or "italic" in face["file"].lower()
    key = (weight, italic)
    g = groups.setdefault(group_key, {"id": fid, "label": label, "family": label, "faces": {}, "zip": face["zip"]})
    if key in g["faces"]:
        continue
    g["faces"][key] = face

# Stable ordering: alphabetical by label, faces by italic then weight.
ordered = sorted(groups.values(), key=lambda g: g["label"].casefold())

css: list[str] = [
    "/* Generated by packages/bangla-fonts — do not hand-edit.",
    " * Every family is bundled locally; no Google Fonts request is made.",
    " * Unicode faces only: legacy ANSI/Bijoy files map Bengali bytes to the",
    " * wrong code points and would render as garbage in a browser.",
    " */",
]
manifest: list[dict] = []


def licence_for(group: dict) -> tuple[list[str], str, str]:
    """Classify the source zip's own terms before bundling anything.

    The family's own document travels with the files. The label is descriptive,
    not a gate: the operator has confirmed the fonts are free to use.
    """
    with zipfile.ZipFile(SRC / group["zip"]) as z:
        docs = [n for n in z.namelist() if re.search(r"(readme|licen[cs]e|terms).*\.(txt|pdf|md)$", n, re.I)]
        text = "\n".join(
            z.read(n).decode("utf-8", "replace")
            for n in docs
            if n.lower().endswith((".txt", ".md"))
        )
    low = text.lower()
    if "lipighor" in low or "লিপিঘর" in text:
        return docs, "web-with-attribution", "webfont allowed with permission and a footer backlink"
    if not docs:
        return docs, "unverified", "no licence document shipped"
    if "fontbd" in low or "webfont" in low or "web font" in low:
        return docs, "prohibited", "terms forbid webfont use"
    return docs, "unverified", "terms do not clearly grant webfont use"


for g in ordered:
    docs, licence, licence_note = licence_for(g)
    faces_out = []
    for (weight, italic), face in sorted(g["faces"].items(), key=lambda kv: (kv[0][0], kv[0][1])):
        style = "italic" if italic else "normal"
        filename = f"{g['id']}-{weight}{'-italic' if italic else ''}.woff2"
        dest = FILES / filename
        with zipfile.ZipFile(SRC / face["zip"]) as z:
            data = z.read(face["file"])
        tmp = OUT / "scripts" / ".font-build-input"
        tmp.write_bytes(data)
        subprocess.run(
            [
                "python", "-m", "fontTools.subset", str(tmp),
                "--unicodes=U+0020-007E,U+00A0-00FF,U+0964-0965,U+0980-09FF,U+200C-200D,U+2010-2027,U+20B9,U+25CC,U+FEFF",
                "--layout-features=*",
                "--flavor=woff2",
                f"--output-file={dest}",
            ],
            check=True,
            capture_output=True,
        )
        tmp.unlink(missing_ok=True)
        faces_out.append({"file": filename, "weight": weight, "style": style})
        css.append(
            "@font-face{"
            f"font-family:'{g['family']}';"
            f"font-style:{style};font-weight:{weight};font-display:swap;"
            f"src:url('./files/{filename}') format('woff2');"
            "}"
        )
    css.append(f".bnfont-{g['id']}{{font-family:'{g['family']}',sans-serif;}}")
    # Keep the family's licence/readme beside the package, not only in the zip.
    with zipfile.ZipFile(SRC / g["zip"]) as z:
        d = LICENSES / g["id"]
        d.mkdir(exist_ok=True)
        for doc in docs:
            (d / Path(doc).name).write_bytes(z.read(doc))
    manifest.append({
        "id": g["id"],
        "label": g["label"],
        "family": g["family"],
        "faces": faces_out,
        "license": licence,
        "licenseNote": licence_note,
    })

(OUT / "fonts.css").write_text("\n".join(css) + "\n", encoding="utf-8")

manifest_ts = '''/**
 * The bundled Bangla type library.
 *
 * Generated from the root `Bangla Fonts` zips; only Unicode faces whose cmap
 * actually contains Bengali are included. `fonts.css` declares the matching
 * @font-face rules, and every surface imports that stylesheet once.
 */
export interface BanglaFontFace {
  file: string;
  weight: number;
  style: "normal" | "italic";
}

export interface BanglaFontFamily {
  /** Stable slug used in settings and CSS class names. */
  id: string;
  /** Human label in the admin picker. */
  label: string;
  /** CSS `font-family` value declared by fonts.css. */
  family: string;
  /** The kind of document shipped with the family. */
  license: "web-with-attribution" | "prohibited" | "unverified";
  licenseNote: string;
  faces: BanglaFontFace[];
}

export const BANGLA_FONTS: readonly BanglaFontFamily[] = ''' + json.dumps(manifest, ensure_ascii=False, indent=2) + ''' as const;

export const BANGLA_FONT_IDS = BANGLA_FONTS.map((f) => f.id);

export function banglaFontById(id: string | null | undefined): BanglaFontFamily | null {
  if (!id) return null;
  return BANGLA_FONTS.find((f) => f.id === id) ?? null;
}

/** A safe stack: the chosen family, then the shipped defaults, then serif. */
export function banglaFontStack(
  id: string | null | undefined,
  fallback = "Noto Serif Bengali",
  generic: "serif" | "sans-serif" = "serif",
): string {
  const font = banglaFontById(id);
  const chosen = font ? `'${font.family}'` : "";
  return [chosen, `'${fallback}'`, generic].filter(Boolean).join(", ");
}
'''
(OUT / "src").mkdir(exist_ok=True)
(OUT / "src" / "index.ts").write_text(manifest_ts, encoding="utf-8")

package_json = {
    "name": "@hoichoi/bangla-fonts",
    "version": "1.0.0",
    "private": True,
    "type": "module",
    "description": "Bundled Unicode Bangla type library used by the web, admin and desktop surfaces.",
    "main": "src/index.ts",
    "types": "src/index.ts",
    "exports": {".": "./src/index.ts", "./fonts.css": "./fonts.css"},
    "files": ["src", "files", "fonts.css", "licenses"],
}
(OUT / "package.json").write_text(json.dumps(package_json, indent=2) + "\n", encoding="utf-8")
(OUT / "README.md").write_text(
    """# @hoichoi/bangla-fonts

Every Unicode Bengali family from the repository's local `Bangla Fonts/` folder,
subset to Bengali + Latin and converted to WOFF2. The web app, the admin console
and the desktop app import `fonts.css` once; nothing is fetched from Google.

- `src/index.ts` — the manifest (`BANGLA_FONTS`, ids, stacks).
- `fonts.css` — generated `@font-face` rules pointing at `files/`.
- `licenses/` — the original readme/terms shipped inside each source zip.

The bundled files are redistributed under each family's own terms; see the
matching folder under `licenses/`. The build never invents a licence for a font
that did not ship one.

The source zips are kept outside git history (20 MB of duplicates); the built
package is self-contained. To regenerate, restore `Bangla Fonts/` at the repo
root and run `python packages/bangla-fonts/scripts/build.py`.
""",
    encoding="utf-8",
)

print(f"families={len(manifest)} faces={sum(len(g['faces']) for g in manifest)}")
print("ids:", ", ".join(g["id"] for g in manifest))
