export const dynamic = "force-dynamic";
export const runtime = "nodejs";
export const maxDuration = 120;

/** Where the local web server reads committed media from (see lib/media.ts). */
function publicUploadsDir(): string {
  return path.join(process.cwd(), "public", "uploads");
}

/**
 * True when generation can be handed to the GitHub Actions runner instead of
 * this request. This is the *only* path that works on the hosted deployment:
 * Vercel freezes `public/` at build time, so bytes written here are never
 * served — the runner mirrors them into `apps/web/public/uploads` and commits
 * that file, and Vercel builds from git.
 */
function runnerConfigured(): boolean {
  return Boolean(process.env.GH_TRIGGER_TOKEN && process.env.GH_REPO);
}

function runnerMissing(): string {
  return (
    "সার্ভারে ছবি-রানার কনফিগার করা নেই — GH_TRIGGER_TOKEN ও GH_REPO (Vercel) সেট করুন, " +
    "অথবা মিডিয়া স্টোরেজ অ্যাডাপ্টার যোগ করুন।"
  );
}

interface GenerateOptions {
  prompt: string;
  providerId: string;
  size: string;
  aspectRatio: string;
  style: string;
  quality: string;
  negativePrompt: string;
}

/**
 * POST `generate-image` options onto the Actions runner (`generate-image.yml`).
 * Returns true when GitHub accepted the dispatch.
 */
async function dispatchToRunner(postId: string, opts: GenerateOptions): Promise<boolean> {
  const res = await fetch(`https://api.github.com/repos/${process.env.GH_REPO}/dispatches`, {
    method: "POST",
    headers: {
      authorization: `Bearer ${process.env.GH_TRIGGER_TOKEN}`,
      "content-type": "application/json",
      accept: "application/vnd.github+json",
    },
    body: JSON.stringify({
      event_type: "generate-image",
      client_payload: {
        post_id: postId,
        prompt: opts.prompt,
        provider: opts.providerId || undefined,
        ratio: opts.aspectRatio || undefined,
        size: opts.size || undefined,
        style: opts.style || undefined,
        quality: opts.quality || undefined,
        negative: opts.negativePrompt || undefined,
      },
    }),
    signal: AbortSignal.timeout(15_000),
  });
  // repository_dispatch answers 204 No Content on success.
  return res.status === 204;
}

/** Persist generated bytes for a dev/local deployment; returns the rel path. */
async function writeLocalMirror(rel: string, bytes: Uint8Array): Promise<void> {
  const dir = publicUploadsDir();
  const full = path.resolve(dir, rel);
  // Throws rather than silently returning: a write that never happened must not
  // look like success to the caller below, which treats it as "served locally".
  if (!full.startsWith(path.resolve(dir))) throw new Error(`illegal media path: ${rel}`);
  await fs.promises.mkdir(path.dirname(full), { recursive: true });
  await fs.promises.writeFile(full, bytes);
}

const DEFAULT_PROMPT_PREFIX =
  "Editorial news illustration, clean modern flat style with soft natural light, dignified print-journalism tone, no text, no logos, no watermarks.";

function bool(v: unknown): boolean {
  return v === true || v === "true" || v === 1 || v === "1";
}

function str(v: unknown): string {
  return typeof v === "string" ? v.trim() : "";
}

/**
 * GET — everything the editor's "generate image" panel needs: the image
 * providers that are active right now, plus a suggested prompt derived from the
 * post so the operator can generate with one click or edit it first.
 */
export async function GET(_req: NextRequest, ctx: { params: Promise<{ id: string }> }) {
  const user = await requireApiUser();
  if (!user) return unauthorized();
  if (user.role !== "admin" && user.role !== "editor") return forbidden();

  const { id } = await ctx.params;
  const post = await getPostById(id);
  if (!post) return NextResponse.json({ error: "post not found" }, { status: 404 });

  const providers = await listImageProviders().catch(() => []);
  const subject = [post.title_bn, post.summary_bn].filter(Boolean).join(" — ").slice(0, 500);
  const suggestedPrompt = subject ? `${DEFAULT_PROMPT_PREFIX}\n\nবিষয়: ${subject}` : DEFAULT_PROMPT_PREFIX;

  return NextResponse.json({
    providers,
    suggestedPrompt,
    aspectRatios: ["1:1", "16:9", "9:16", "4:3", "3:4", "3:2"],
    sizes: ["1024x1024", "1024x1792", "1792x1024", "1536x1024", "1024x1536"],
    styles: ["natural", "vivid"],
    qualities: ["standard", "hd", "low", "medium", "high"],
    /** "runner" = generate in GitHub Actions and commit the file; "local" = do it here. */
    via: runnerConfigured() ? "runner" : "local",
    /** Current media reference, so the editor can poll until a queued image lands. */
    media_path: post.media_path ?? null,
  });
}

/**
 * POST — generate an image for a post and attach it.
 *
 * Body: { prompt?, providerId?, aspectRatio?, size?, style?, quality?,
 *         negativePrompt?, count?, useTitle?, attach? }
 *
 * Two paths, decided by `GH_TRIGGER_TOKEN` + `GH_REPO`:
 *
 *  1. **Runner (hosted default).** The request dispatches `generate-image.yml`,
 *     which runs the scraper's `media generate` CLI in Actions. The CLI mirrors
 *     the image into `apps/web/public/uploads`, attaches it to the post, and the
 *     workflow commits the file — the only way a serverless deploy can serve it.
 *     The response is `{ queued: true }`; the editor polls `media_path` and then
 *     the image URL until Vercel has rebuilt.
 *
 *  2. **In-process (local/dev).** The bytes are generated here and pushed to the
 *     remote storage adapter chain, falling back to the local `public/uploads`
 *     store. If neither can persist them (serverless filesystem, no adapter),
 *     the route returns 501 with a pointer at the setup guide instead of
 *     attaching a path that would 404 on the deployed site.
 *
 * On success the post's `media_path` is updated through the validated
 * `updatePost` path and an `admin_actions` row records it.
 */
export async function POST(req: NextRequest, ctx: { params: Promise<{ id: string }> }) {
  const user = await requireApiUser();
  if (!user) return unauthorized();
  if (user.role !== "admin" && user.role !== "editor") return forbidden();

  const { id } = await ctx.params;
  const post = await getPostById(id);
  if (!post) return NextResponse.json({ error: "post not found" }, { status: 404 });

  const body = (await req.json().catch(() => null)) as Record<string, unknown> | null;
  const useTitle = body ? bool(body.useTitle) : true;
  let prompt = str(body?.prompt);
  if (!prompt && useTitle) {
    const subject = [post.title_bn, post.summary_bn].filter(Boolean).join(" — ").slice(0, 500);
    prompt = subject ? `${DEFAULT_PROMPT_PREFIX}\n\nবিষয়: ${subject}` : DEFAULT_PROMPT_PREFIX;
  }
  if (!prompt) {
    return NextResponse.json({ error: "প্রম্পট প্রয়োজন (অথবা useTitle পাঠান)" }, { status: 400 });
  }

  const opts: GenerateOptions = {
    prompt,
    providerId: str(body?.providerId),
    size: str(body?.size),
    aspectRatio: str(body?.aspectRatio),
    style: str(body?.style),
    quality: str(body?.quality),
    negativePrompt: str(body?.negativePrompt),
  };
  const attach = body ? bool(body.attach) || body.attach === undefined : true;

  // Hosted deployments hand generation to the Actions runner: it is the only
  // place that can persist bytes the deployed site will actually serve. The
  // request returns immediately and the editor polls `media_path` until the
  // runner has attached the image and Vercel has rebuilt.
  if (runnerConfigured()) {
    let dispatched = false;
    try {
      dispatched = await dispatchToRunner(id, opts);
    } catch {
      dispatched = false;
    }
    if (dispatched) {
      const client = getClient();
      if (attach) {
        await client.execute({
          sql: "INSERT INTO admin_actions (id, admin_user_id, action, target_table, target_id, details, created_at) VALUES (?, ?, ?, 'posts', ?, ?, ?)",
          args: [
            crypto.randomUUID(),
            user.user_id,
            "post.generate_image_queued",
            id,
            JSON.stringify({ prompt: opts.prompt, by: user.email, via: "runner" }),
            nowIso(),
          ],
        });
      }
      return NextResponse.json({
        ok: true,
        queued: true,
        via: "runner",
        attached: attach,
        message: "ছবি তৈরি হচ্ছে GitHub Actions-এ — ১–৩ মিনিট পর এই প্যানেলটি নিজে থেকেই হালনাগাদ হবে।",
      });
    }
    // Dispatch failed (token revoked, repo renamed, network): fall through to
    // in-process generation so a locally runnable dev setup still works.
  }

  let result;
  try {
    result = await generateImage(
      {
        prompt: opts.prompt,
        providerId: opts.providerId || undefined,
        size: opts.size || undefined,
        aspectRatio: opts.aspectRatio || undefined,
        style: opts.style || undefined,
        quality: opts.quality || undefined,
        negativePrompt: opts.negativePrompt || undefined,
        count: 1,
      },
      AbortSignal.timeout(110_000),
    );
  } catch (err) {
    return NextResponse.json({ error: (err as Error).message }, { status: 502 });
  }

  const buf = Buffer.from(result.bytes);
  const rel = randomMediaName("img", extensionForMime(result.contentType));

  let applied: string | null = null;
  let stored: "remote" | "local" = "local";
  try {
    const url = await uploadBufferRemote(rel, buf, id);
    if (url) {
      applied = url;
      stored = "remote";
    }
  } catch {
    /* fall through to local store */
  }
  if (!applied) {
    try {
      await writeGeneratedMedia(rel, buf);
    } catch {
      /* media root may be read-only; the public mirror below is enough locally */
    }
    // Only accept the relative path when this runtime can actually serve it.
    // On Vercel `public/` is build-time frozen, so a successful-looking write
    // here would attach a 404 to the post — which is exactly what "image does
    // not show" looked like.
    try {
      await writeLocalMirror(rel, result.bytes);
      applied = rel;
    } catch {
      return NextResponse.json(
        {
          ok: false,
          error: `${runnerMissing()} (এই পরিবেশে ছবিটি সংরক্ষণ করা যায়নি)`,
          setupGuide: "/admin/setup",
        },
        { status: 501 },
      );
    }
  }

  if (attach) {
    try {
      await updatePost(id, { media_path: applied });
    } catch (err) {
      return NextResponse.json({ error: (err as Error).message }, { status: 400 });
    }
    const client = getClient();
    await client.execute({
      sql: "INSERT INTO admin_actions (id, admin_user_id, action, target_table, target_id, details, created_at) VALUES (?, ?, ?, 'posts', ?, ?, ?)",
      args: [
        crypto.randomUUID(),
        user.user_id,
        "post.generate_image",
        id,
        JSON.stringify({ media_path: applied, provider: result.provider, model: result.model, prompt: result.prompt }),
        nowIso(),
      ],
    });
  }

  return NextResponse.json({
    ok: true,
    media_path: applied,
    stored,
    via: "local",
    provider: result.provider,
    model: result.model,
    contentType: result.contentType,
    bytes: result.bytes.length,
    attached: attach,
  });
}
